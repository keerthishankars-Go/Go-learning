//A variable can also be initialized with a value when it is declared. The following is the syntax to declare a variable with an initial value.

// "var name type = initialvalue"

package main

import "fmt"

func main() {
	var age int = 27 //variable declaration with initial value

	fmt.Println("My initial age is", age)
}

//In the above program, age is a variable of type int and has initial value 27.

//It confirms that age has been initialized with the value 27.
