package main

import (
	"fmt"
)

func main() {
	var a [3]int // int array with length 3
	fmt.Println(a)
}

// var a [3]int declares an integer array of length 3. All elements in an array are automatically assigned the zero value of the array type. In this case a is an integer array and hence all elements of a are assigned to 0, the zero value of int.

// Running the above program will print:

// [0 0 0]
